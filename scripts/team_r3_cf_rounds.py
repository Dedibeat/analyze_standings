#!/usr/bin/env python3
"""Round-by-round digests of NUM-R^3 members' Codeforces entries, against the real field.

    python3 scripts/team_r3_cf.py          # first: builds output/team_r3_cf.json
    python3 scripts/team_r3_cf_rounds.py   # fetches what is missing, then prints and writes the digests

Rounds covered (about 20 rated rounds each, plus every 2026 virtual):
  Dedi: rated rounds since 2025-11-05; Erdene: rated rounds since 2025-07-01 (both handles);
  Tamir: all rated rounds.

For each entry, using the full official standings (`contest.standings`, anonymous call):
  field solves and median solve minute per problem; the "same set" tier (official contestants who
  solved exactly our problems) and our place in it; the "next tier" (our set plus exactly one more
  problem): their median minutes on our problems and which extra problem they solved; the field's
  next problem for us, with its editorial (sibling repo ../codeforces_integration, cloudscraper).
Virtual entries are placed in the official standings by recomputing our score with the round's own
rules (CF points decay fitted on the standings; ICPC-style penalty 10 min per wrong try).

Caches (gitignored, rebuildable): data/team_r3/cf/standings/<cid>.json.gz (compact rows),
data/team_r3/cf/editorials/<cid><index>.json. Output: output/team_r3_cf_rounds.json and the
one-row-per-entry tables output/team_r3_cf_rounds.md (the analysis is output/team_r3_coach/cf_rounds.md).
"""
import collections
import json
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from team_r3_cf import standings  # noqa: E402  (shared cache of official standings)

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "data" / "team_r3" / "cf"
EDIT = D / "editorials"
OUT = ROOT / "output" / "team_r3_cf_rounds.json"
OUT_MD = ROOT / "output" / "team_r3_cf_rounds.md"
SIBLING = ROOT.parent / "codeforces_integration"
ts = lambda y, m, d: datetime(y, m, d, tzinfo=timezone.utc).timestamp()
RATED_FROM = {"Dedi": ts(2025, 11, 5), "Erdene": ts(2025, 7, 1), "Tamir": 0}
VIRTUAL_FROM = ts(2026, 1, 1)


def editorial(cid, index):
    f = EDIT / f"{cid}{index}.json"
    if f.exists():
        return json.loads(f.read_text())
    EDIT.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(SIBLING))
    from cf_problems.models import ProblemMeta
    from cf_problems.scraper import Scraper
    from cf_problems.transport import build_session
    try:
        e = Scraper(session=build_session(), delay=2.0).fetch_editorial(ProblemMeta(contest_id=cid, index=index, name=""))
        rec = {"url": e.url if e else None, "tutorial": e.tutorial if e else None}
    except Exception as exc:  # recorded, not fatal: the digest just has no editorial text
        rec = {"url": None, "tutorial": None, "error": str(exc)}
    f.write_text(json.dumps(rec, ensure_ascii=False))
    return rec


def cf_decay(st):
    """Points lost per minute per point of max value, fitted on rows (CF rules: P*(1 - m/c) - 50*w)."""
    best = None
    for c in range(150, 501, 10):
        err = 0
        for row in st["rows"][:400]:
            for (sec, rej, pts), q in zip(row[3], st["problems"]):
                if sec >= 0 and q["points"]:
                    P = q["points"]
                    err += abs(max(0.3 * P, P * (1 - (sec // 60) / c) - 50 * rej) - pts) > 1
        if best is None or err < best[0]:
            best = (err, c)
    return best[1]


def write_tables(digests, penalty_check):
    icpc = [x for x in penalty_check if x[1] == "ICPC"]
    worst_cf = max((abs(a - b) for _, r, a, b in penalty_check if r == "CF"), default=0)
    md = ["# NUM-R^3 on Codeforces: one row per round (generated by scripts/team_r3_cf_rounds.py)", "",
          "Columns: **exp** = solves expected at the member's level for that half-year; **same set** = our place",
          "among official contestants who solved exactly our problems (ahead of us / all); **slowest vs next tier** =",
          "our problem with the largest gap to the median minute of contestants who solved our set plus one more;",
          "**next** = the extra problem most of that next tier solved (the field's next problem for us), with its",
          "rating and our tries. Virtual entries are placed in the official standings by recomputing our score.",
          f"Recomputation check on our {len(penalty_check)} rated entries: ICPC-rules rounds "
          f"{sum(abs(a - b) <= 0 for _, _, a, b in icpc)}/{len(icpc)} exact once test-1 rejections are not counted "
          f"(Codeforces does not count them); CF-rules rounds within {worst_cf:.0f} points.", ""]
    for member, ds in digests.items():
        md += [f"## {member} ({len(ds)} entries)", "",
               "| date | contest | kind | Δ | rank / field | solved | exp | same set | wrong (test 1) | slowest vs next tier | next (rating, our tries) |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        for d in ds:
            ours = [q for q in d["problems"] if q["ours_min"] is not None]
            gaps = [(q["ours_min"] - q["next_tier_median_min"], q) for q in ours if q["next_tier_median_min"] is not None]
            g = max(gaps, key=lambda x: x[0]) if gaps else None
            slow = f"{g[1]['index']} {g[1]['ours_min']}′ vs {g[1]['next_tier_median_min']}′" if g and g[0] > 0 else "—"
            wrong = sum(q["tries"] for q in d["problems"]); t1 = sum(q["test1"] for q in d["problems"])
            nq = next((q for q in d["problems"] if q["index"] == d["next_problem"]), None)
            nxt = f"{nq['index']} ({nq['rating'] or '?'}, {nq['tries']})" if nq else "—"
            delta = f"{d['delta']:+d}" if d["delta"] is not None else ""
            md.append(f"| {d['date']} | {d['contest_id']} {d['division']} | {d['kind']} | {delta} | {d['rank']} / {d['field']} | "
                      f"{d['solved']} | {d['expected_solves'] if d['expected_solves'] is not None else '?'} | "
                      f"{d['ahead_in_same_set']} / {d['same_set']} | {wrong} ({t1}) | {slow} | {nxt} |")
        md.append("")
    OUT_MD.write_text("\n".join(md))


def main():
    data = json.loads((ROOT / "output" / "team_r3_cf.json").read_text())
    levels = data["members"]
    sel = [r for r in data["participations"] if r["division"] != "gym" and r["rules"] in ("CF", "ICPC") and (
        (r["kind"] == "rated" and r["start"] >= RATED_FROM[r["member"]]) or
        (r["kind"] == "virtual" and r["start"] >= VIRTUAL_FROM))]
    digests = collections.defaultdict(list)
    penalty_check = []
    for r in sorted(sel, key=lambda r: r["start"]):
        st = standings(r["contest_id"])
        probs = [q["index"] for q in st["problems"]]
        mine = {q["index"]: q for q in r["problems"]}
        rows = st["rows"]
        n = len(rows)
        field = {}
        for i, L in enumerate(probs):
            secs = [row[3][i][0] for row in rows if row[3][i][0] >= 0]
            field[L] = (len(secs), round(statistics.median(secs) / 60) if secs else None)
        ours_set = frozenset(L for L in probs if mine.get(L, {}).get("solved"))
        solved_sets = [frozenset(L for i, L in enumerate(probs) if row[3][i][0] >= 0) for row in rows]

        # our score on the official scale
        rules = st["contest"]["type"]
        decay = cf_decay(st) if rules == "CF" else None
        def score(prob_list):
            if rules == "ICPC":
                return (len(prob_list), -sum(m + 10 * w for m, w in prob_list.values()))
            pts = 0
            for L, (m, w) in prob_list.items():
                P = st["problems"][probs.index(L)]["points"] or 0
                pts += max(0.3 * P, P * (1 - m / decay) - 50 * w)
            return (pts,)
        # Codeforces does not count a rejection on test 1, under either rule set; penalty_check below
        # verifies this against the official rows of our rated entries.
        def counted(q):
            return q["tries"] - len(q["test1"])
        mine_score = score({L: (mine[L]["ac_min"], counted(mine[L])) for L in ours_set})
        row_key = (lambda row: (row[1],)) if rules == "CF" else (lambda row: (sum(1 for c in row[3] if c[0] >= 0), -row[2]))
        if r["kind"] == "rated" and r["handle"] in st["ours"]:
            off = st["ours"][r["handle"]]
            penalty_check.append((r["contest_id"], rules, round(mine_score[-1]), off[1] if rules == "CF" else -off[2]))
            rank = off[0]
        else:
            rank = 1 + sum(1 for row in rows if row_key(row) > tuple(round(x, 6) for x in mine_score))
        same = [row for row, s in zip(rows, solved_sets) if s == ours_set]
        better_same = sum(1 for row in same if row[0] < rank)
        nxt = [(row, s) for row, s in zip(rows, solved_sets) if ours_set < s and len(s) == len(ours_set) + 1]
        extra = collections.Counter(next(iter(s - ours_set)) for _, s in nxt)
        next_med = {}
        for L in sorted(ours_set | set(extra)):
            i = probs.index(L)
            v = [row[3][i][0] for row, _ in nxt if row[3][i][0] >= 0]
            next_med[L] = round(statistics.median(v) / 60) if v else None
        nxt_prob = extra.most_common(1)[0][0] if extra else None
        th = levels[r["member"]]["theta_by_half_year"].get(
            f"{datetime.fromtimestamp(r['start'], timezone.utc).year}H{1 + (datetime.fromtimestamp(r['start'], timezone.utc).month - 1) // 6}")
        s_fix = (levels[r["member"]]["level_rated"] or [0, 200])[1]
        exp = sum(1 / (1 + 10 ** 0 * __import__("math").exp((q["rating"] - th) / s_fix))
                  for q in r["problems"] if q["rating"]) if th else None
        ed = editorial(r["contest_id"], nxt_prob) if nxt_prob else None
        digests[r["member"]].append({
            "contest_id": r["contest_id"], "name": st["contest"]["name"], "date": datetime.fromtimestamp(r["start"], timezone.utc).date().isoformat(),
            "kind": r["kind"], "handle": r["handle"], "rules": rules, "division": r["division"],
            "delta": (r["new"] - r["old"]) if "new" in r else None, "rank": rank, "field": n,
            "solved": "".join(sorted(ours_set, key=probs.index)), "expected_solves": round(exp, 1) if exp else None,
            "problems": [{"index": L, "rating": mine.get(L, {}).get("rating"), "field_solved": field[L][0],
                          "field_median_min": field[L][1], "ours_min": mine.get(L, {}).get("ac_min"),
                          "tries": mine.get(L, {}).get("tries", 0), "test1": len(mine.get(L, {}).get("test1", [])),
                          "verdicts": mine.get(L, {}).get("verdicts", []), "try_ids": mine.get(L, {}).get("try_ids", []),
                          "next_tier_median_min": next_med.get(L)} for L in probs],
            "same_set": len(same), "ahead_in_same_set": better_same, "next_tier": len(nxt),
            "next_problem": nxt_prob, "next_problem_share_of_next_tier": round(extra[nxt_prob] / len(nxt), 2) if nxt else None,
            "editorial": ed})

    OUT.write_text(json.dumps({"rounds": digests, "penalty_check": penalty_check}, ensure_ascii=False, indent=1))
    write_tables(digests, penalty_check)
    ok = sum(1 for _, _, a, b in penalty_check if abs(a - b) <= 2)
    print(f"score recomputation vs official, rated entries: {ok}/{len(penalty_check)} within 2 points/minutes")
    for cid, rules, a, b in penalty_check:
        if abs(a - b) > 2:
            print(f"  mismatch {cid} {rules}: recomputed {a}, official {b}")
    for member, ds in digests.items():
        print(f"\n===== {member}: {len(ds)} entries")
        for d in ds:
            print(f"\n{d['date']} {d['contest_id']} {d['name'][:60]} [{d['kind']}, {d['rules']}] "
                  f"rank {d['rank']}/{d['field']} delta {d['delta']} solved {d['solved']} (expected {d['expected_solves']}) "
                  f"same set {d['same_set']} (ahead of us {d['ahead_in_same_set']}), next tier {d['next_tier']}, "
                  f"next problem {d['next_problem']} ({d['next_problem_share_of_next_tier']})")
            for q in d["problems"]:
                if q["field_solved"] == 0 and not q["tries"]:
                    continue
                print(f"   {q['index']:3} r{q['rating']} field {q['field_solved']:5} med {q['field_median_min']} | "
                      f"ours {q['ours_min']} tries {q['tries']} (t1 {q['test1']}) {q['verdicts'][:4]} | next-tier med {q['next_tier_median_min']}")


if __name__ == "__main__":
    main()
