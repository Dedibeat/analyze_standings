"""EC-Final medal lines for the 51st season, and every EC-Final tier against every
regional tier.  No ratings: reuses the XCPCIO boards, team links and the own
Bradley-Terry fit of ``ecf_vs_regional_gold.py`` (48th-50th seasons).

1. Model-free cross table: regional result x EC-Final result for the same teams.
2. Own fit, both directions: each regional tier line (cutoff cohort, ranks
   cutoff+-2) placed in the EC-Final field, and each EC-Final tier line placed in
   each regional's field (expected official rank, then the tier it would get).
3. 51st forecast: the raw EC-Final lines (solved, penalty at official ranks
   28/84/168) of the 48th-50th finals, and the tier map pooled over the seasons.
   The 51st EC-Final has not been held; its medal counts are assumed to stay
   28/56/84 as in all three previous finals.

    python scripts/ecf_tier_cross.py
"""

import os
import statistics
import sys
from collections import defaultdict

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
import ecf_vs_regional_gold as base  # noqa: E402

OUT = os.path.join(base.ROOT, "output", "ecf_tier_cross.md")
TIERS = ["gold", "silver", "bronze"]
ALL = TIERS + ["none"]


def tier_of(rank, cut):
    return next((t for t in TIERS if rank <= cut[t]), "none")


def cohort_keys(bd, cut, linked):
    rows = bd["rows"][max(0, cut - 1 - base.COHORT): cut + base.COHORT]
    return [("ecfinal", linked[(bd["site"], r["id"])]["id"])
            if (bd["site"], r["id"]) in linked else (bd["site"], r["id"]) for r in rows]


def expected_rank(x, field):
    return 1 + float(np.sum(1 / (1 + np.exp(x - field))))


def main():
    cross = defaultdict(int)                       # (regional tier, ecf tier) -> appearances
    reg_in_ecf = defaultdict(list)                 # regional tier -> expected ECF ranks
    ecf_in_reg = defaultdict(list)                 # ecf tier -> (regional tier, rank pct)
    raw = []
    for season, sites in base.SEASONS.items():
        ecf = base.load_board(season, "ecfinal")
        regs = [r for r in (base.load_board(season, s) for s in sites) if r["start"] < ecf["start"]]
        linked = base.link(ecf, regs)
        for reg in regs:
            for r in reg["rows"]:
                e = linked.get((reg["site"], r["id"]))
                if e:
                    cross[(r["tier"], e["tier"])] += 1

        s = base.bradley_terry([ecf] + regs, linked)
        ecf_field = np.array([s[("ecfinal", e["id"])] for e in ecf["rows"] if e["solved"] > 0])
        ecut = ecf["cut"]
        for reg in regs:
            for t in TIERS:
                x = np.mean([s[k] for k in cohort_keys(reg, reg["cut"][t], linked)])
                reg_in_ecf[t].append((season, reg["site"], expected_rank(x, ecf_field)))
            field = np.array([s[("ecfinal", linked[(reg["site"], r["id"])]["id"])]
                              if (reg["site"], r["id"]) in linked else s[(reg["site"], r["id"])]
                              for r in reg["rows"] if r["solved"] > 0])
            for t in TIERS:
                x = np.mean([s[k] for k in cohort_keys(ecf, ecut[t], {})])
                rk = expected_rank(x, field)
                ecf_in_reg[t].append((season, reg["site"], rk, tier_of(rk, reg["cut"]),
                                      rk / len(reg["rows"])))
        for t in TIERS:
            r = ecf["rows"][ecut[t] - 1]
            raw.append((season, t, ecut[t], r["solved"], r["penalty"] // 60))

    L = ["# EC-Final tiers vs regional tiers, and the 51st EC-Final lines (no ratings)", "",
         "Generated by `scripts/ecf_tier_cross.py` from the official XCPCIO boards of the "
         "48th-50th seasons (21 regionals, 3 EC-Finals). EC-Final lines are official ranks "
         "28 / 84 / 168 (gold / silver / bronze).", "",
         "## 1. Same teams, regional result x EC-Final result (all seasons)", "",
         "Each row is a regional appearance of a team that later played that season's EC-Final.", "",
         "| regional \\ EC-Final | gold | silver | bronze | none | n |", "|---|---|---|---|---|---|"]
    for rt in ALL:
        n = sum(cross[(rt, et)] for et in ALL)
        L.append(f"| {rt} | " + " | ".join(f"{cross[(rt, et)]} ({cross[(rt, et)] / max(1, n):.0%})"
                                          for et in ALL) + f" | {n} |")
    L += ["", "## 2a. Regional lines placed in the EC-Final field (own fit)", "",
          "Expected EC-Final official rank of each regional's cutoff cohort "
          "(EC-Final silver line 84, bronze line 168).", "",
          "| regional line | median | range | EC-Final tier of median | regionals per EC-Final tier (g/s/b/none) |",
          "|---|---|---|---|---|"]
    ecut = {"gold": 28, "silver": 84, "bronze": 168}
    for t in TIERS:
        ranks = [r for _, _, r in reg_in_ecf[t]]
        cnt = [sum(tier_of(r, ecut) == x for r in ranks) for x in ALL]
        L.append(f"| regional {t} | {statistics.median(ranks):.0f} | {min(ranks):.0f}-{max(ranks):.0f} "
                 f"| {tier_of(statistics.median(ranks), ecut)} | {'/'.join(map(str, cnt))} |")
    L += ["", "## 2b. EC-Final lines placed in each regional's field (own fit)", "",
          "Expected official rank at each regional, as a share of that regional's official field, "
          "and the regional tier it would earn.", "",
          "| EC-Final line | median regional rank | median share of field | regional tier (g/s/b/none over 21) |",
          "|---|---|---|---|"]
    for t in TIERS:
        v = ecf_in_reg[t]
        cnt = [sum(x[3] == y for x in v) for y in ALL]
        L.append(f"| EC-Final {t} | {statistics.median(x[2] for x in v):.0f} | "
                 f"{statistics.median(x[4] for x in v):.1%} | {'/'.join(map(str, cnt))} |")
    L += ["", "Per regional (expected rank of the EC-Final line cohort):", "",
          "| season | regional | ECF gold line | ECF silver line | ECF bronze line | regional cuts g/s/b |",
          "|---|---|---|---|---|---|"]
    per = defaultdict(dict)
    for t in TIERS:
        for season, site, rk, tr, _ in ecf_in_reg[t]:
            per[(season, site)][t] = f"{rk:.0f} ({tr})"
    cuts = {}
    for season, sites in base.SEASONS.items():
        for site in sites:
            c = base.load_board(season, site)["cut"]
            cuts[(season, site)] = f"{c['gold']}/{c['silver']}/{c['bronze']}"
    for k, v in per.items():
        L.append(f"| {k[0]} | {k[1]} | {v['gold']} | {v['silver']} | {v['bronze']} | {cuts[k]} |")
    L += ["", "## 3. EC-Final lines in solves and penalty (48th-50th) and the 51st forecast", "",
          "| season | line | official rank | solved | penalty (min) |", "|---|---|---|---|---|"]
    for season, t, rk, sv, pen in raw:
        L.append(f"| {season} | {t} | {rk} | {sv} | {pen} |")
    L += ["", "51st EC-Final forecast (not held yet; medal counts assumed 28/56/84). The solve "
          "count depends on the problem set, so the range of the last three finals is given; "
          "the regional equivalent (section 2b) is the steadier statement:", ""]
    for t in TIERS:
        sv = [x[3] for x in raw if x[1] == t]
        v = ecf_in_reg[t]
        L.append(f"- **{t}**: {min(sv)}-{max(sv)} solved; about regional rank "
                 f"{statistics.median(x[2] for x in v):.0f} "
                 f"(top {statistics.median(x[4] for x in v):.0%} of a regional's official field).")
    L.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
